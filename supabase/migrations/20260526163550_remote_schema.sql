CREATE OR REPLACE FUNCTION "public"."equipo_disponible_en_franja"("p_equipo_id" "uuid", "p_fecha" "date", "p_inicio" time without time zone, "p_fin" time without time zone, "p_exclude_reserva_id" "uuid" DEFAULT NULL::"uuid") RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    AS $$
  SELECT NOT EXISTS (
    SELECT 1
    FROM public.reserva_equipos re
    JOIN public.reservas r ON r.id = re.reserva_id
    WHERE re.equipo_id = p_equipo_id
      AND r.fecha      = p_fecha
      AND r.estado     IN ('pendiente', 'confirmada')
      AND (p_exclude_reserva_id IS NULL OR r.id <> p_exclude_reserva_id)
      AND r.hora_inicio < p_fin
      AND r.hora_fin    > p_inicio
  )
  AND NOT EXISTS (
    SELECT 1
    FROM public.prestamos_equipo pe
    WHERE pe.equipo_id = p_equipo_id
      AND pe.estado    = 'activo'
      AND pe.fecha_inicio     <= (p_fecha::TEXT || 'T' || p_fin::TEXT   || '-05:00')::TIMESTAMPTZ
      AND pe.fecha_fin_esperada > (p_fecha::TEXT || 'T' || p_inicio::TEXT || '-05:00')::TIMESTAMPTZ
  );
$$;


