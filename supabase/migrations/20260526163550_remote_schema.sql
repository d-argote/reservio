CREATE OR REPLACE FUNCTION "public"."recalcular_estado_sala"("p_sala_id" "uuid") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
DECLARE
  v_fecha  DATE   := (NOW() AT TIME ZONE 'America/Bogota')::DATE;
  v_hora   TIME   := (NOW() AT TIME ZONE 'America/Bogota')::TIME;
  v_count  INT;
  v_nuevo  TEXT;
BEGIN
  -- Si está en mantenimiento, no cambiar
  PERFORM 1 FROM public.salas WHERE id = p_sala_id AND estado = 'mantenimiento';
  IF FOUND THEN RETURN; END IF;

  SELECT COUNT(*) INTO v_count
  FROM public.reservas
  WHERE sala_id    = p_sala_id
    AND fecha      = v_fecha
    AND estado     IN ('pendiente', 'confirmada')
    AND hora_inicio <= v_hora
    AND hora_fin    >  v_hora;

  v_nuevo := CASE WHEN v_count > 0 THEN 'ocupada' ELSE 'disponible' END;

  UPDATE public.salas SET estado = v_nuevo WHERE id = p_sala_id;
END;
$$;


