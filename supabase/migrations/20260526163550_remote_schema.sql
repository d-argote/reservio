CREATE OR REPLACE FUNCTION "public"."fn_check_equipo_overlap"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_count int;
BEGIN
  IF NEW.estado != 'activo' THEN
    RETURN NEW;
  END IF;

  -- Serialize concurrent loan attempts for the same equipment
  PERFORM pg_advisory_xact_lock(hashtext(NEW.equipo_id::text), 0);

  SELECT COUNT(*) INTO v_count
  FROM prestamos_equipo
  WHERE equipo_id = NEW.equipo_id
    AND estado    = 'activo'
    AND id        IS DISTINCT FROM NEW.id
    AND fecha_inicio       < NEW.fecha_fin_esperada
    AND fecha_fin_esperada > NEW.fecha_inicio;

  IF v_count > 0 THEN
    RAISE EXCEPTION 'El equipo ya tiene un préstamo activo en ese horario. Elige otro equipo o un horario diferente.'
      USING ERRCODE = '23P01';
  END IF;

  RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."fn_check_equipo_overlap"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."fn_check_sala_overlap"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_count int;
BEGIN
  IF NEW.estado NOT IN ('pendiente', 'confirmada') THEN
    RETURN NEW;
  END IF;

  -- Acquire a transaction-level exclusive advisory lock keyed to (room, date).
  -- Two transactions for the same room+date cannot both hold this lock.
  PERFORM pg_advisory_xact_lock(
    hashtext(NEW.sala_id::text),
    (NEW.fecha::date - '2000-01-01'::date)
  );

  SELECT COUNT(*) INTO v_count
  FROM reservas
  WHERE sala_id = NEW.sala_id
    AND fecha   = NEW.fecha
    AND estado IN ('pendiente', 'confirmada')
    AND id      IS DISTINCT FROM NEW.id   -- exclude self on UPDATE
    AND hora_inicio < NEW.hora_fin
    AND hora_fin    > NEW.hora_inicio;

  IF v_count > 0 THEN
    RAISE EXCEPTION 'La sala ya tiene una reserva en ese horario. Elige otra franja horaria.'
      USING ERRCODE = '23P01';
  END IF;

  RETURN NEW;
END;
$$;


