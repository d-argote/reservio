CREATE OR REPLACE FUNCTION "public"."fn_recalcular_equipo_estado"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_equipo_id  uuid;
  v_ahora      timestamptz;
  v_count      int;
BEGIN
  v_equipo_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.equipo_id ELSE NEW.equipo_id END;

  -- Skip equipment in mantenimiento
  IF EXISTS (SELECT 1 FROM equipos WHERE id = v_equipo_id AND estado = 'mantenimiento') THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  v_ahora := now();

  -- Count active loans currently in progress for this equipment
  SELECT COUNT(*) INTO v_count
  FROM prestamos_equipo
  WHERE equipo_id = v_equipo_id
    AND estado = 'activo'
    AND fecha_inicio       <= v_ahora
    AND fecha_fin_esperada >  v_ahora;

  UPDATE equipos
     SET estado = CASE WHEN v_count > 0 THEN 'reservado' ELSE 'disponible' END
   WHERE id = v_equipo_id;

  RETURN COALESCE(NEW, OLD);
END;
$$;


ALTER FUNCTION "public"."fn_recalcular_equipo_estado"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."fn_recalcular_sala_estado"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_sala_id  uuid;
  v_bogota   timestamp;
  v_fecha    text;
  v_time     text;
  v_count    int;
BEGIN
  -- Determine which sala changed
  v_sala_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.sala_id ELSE NEW.sala_id END;

  -- Skip rooms explicitly set to mantenimiento
  IF EXISTS (SELECT 1 FROM salas WHERE id = v_sala_id AND estado = 'mantenimiento') THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  -- Current time in Bogotá (America/Bogota = UTC-5, no DST)
  v_bogota := now() AT TIME ZONE 'America/Bogota';
  v_fecha  := to_char(v_bogota, 'YYYY-MM-DD');
  v_time   := to_char(v_bogota, 'HH24:MI');

  -- Count reservations active right now for this room
  SELECT COUNT(*) INTO v_count
  FROM reservas
  WHERE sala_id = v_sala_id
    AND fecha::text = v_fecha
    AND estado IN ('pendiente', 'confirmada')
    AND hora_inicio::text <= v_time
    AND hora_fin::text    >  v_time;

  UPDATE salas
     SET estado = CASE WHEN v_count > 0 THEN 'ocupada' ELSE 'disponible' END
   WHERE id = v_sala_id;

  RETURN COALESCE(NEW, OLD);
END;
$$;


