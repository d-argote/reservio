CREATE OR REPLACE FUNCTION "public"."recalcular_estado_equipo"("p_equipo_id" "uuid") RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
DECLARE
  v_ahora  TIMESTAMPTZ := NOW();
  v_count  INT;
  v_nuevo  TEXT;
BEGIN
  -- Si está en mantenimiento, no cambiar
  PERFORM 1 FROM public.equipos WHERE id = p_equipo_id AND estado = 'mantenimiento';
  IF FOUND THEN RETURN; END IF;

  -- Contar préstamos activos EN CURSO ahora mismo
  SELECT COUNT(*) INTO v_count
  FROM public.prestamos_equipo
  WHERE equipo_id          = p_equipo_id
    AND estado             = 'activo'
    AND fecha_inicio       <= v_ahora
    AND fecha_fin_esperada >  v_ahora;

  v_nuevo := CASE WHEN v_count > 0 THEN 'reservado' ELSE 'disponible' END;

  UPDATE public.equipos SET estado = v_nuevo WHERE id = p_equipo_id;
END;
$$;


